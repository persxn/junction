CREATE TABLE `engagement_outcomes` (
	`engagement_id` text PRIMARY KEY NOT NULL,
	`result` text NOT NULL,
	`rank` integer,
	`prize_text` text,
	`prize_minor` integer,
	`prize_currency` text,
	`certificate_resource_id` text,
	`result_url` text,
	`notes` text,
	`feedback` text,
	`recorded_by` text NOT NULL,
	`recorded_at` integer NOT NULL,
	`version` integer DEFAULT 1 NOT NULL,
	FOREIGN KEY (`engagement_id`) REFERENCES `engagements`(`id`) ON UPDATE no action ON DELETE no action,
	FOREIGN KEY (`certificate_resource_id`) REFERENCES `resources`(`id`) ON UPDATE no action ON DELETE set null,
	FOREIGN KEY (`recorded_by`) REFERENCES `users`(`id`) ON UPDATE no action ON DELETE no action,
	CONSTRAINT "engagement_outcomes_result_check" CHECK("result" in ('PARTICIPATED', 'DID_NOT_PARTICIPATE', 'QUALIFIED', 'FINALIST', 'RUNNER_UP', 'WINNER', 'OTHER')),
	CONSTRAINT "engagement_outcomes_rank_check" CHECK("rank" is null or "rank" >= 1),
	CONSTRAINT "engagement_outcomes_prize_check" CHECK(("prize_minor" is null and "prize_currency" is null) or ("prize_minor" is not null and "prize_currency" is not null and "prize_minor" >= 0 and "prize_currency" glob '[A-Z][A-Z][A-Z]')),
	CONSTRAINT "engagement_outcomes_prize_text_check" CHECK("prize_text" is null or length("prize_text") <= 200),
	CONSTRAINT "engagement_outcomes_result_url_check" CHECK("result_url" is null or "result_url" like 'http://%' or "result_url" like 'https://%'),
	CONSTRAINT "engagement_outcomes_text_check" CHECK(("notes" is null or length("notes") <= 2000) and ("feedback" is null or length("feedback") <= 2000)),
	CONSTRAINT "engagement_outcomes_version_check" CHECK("version" >= 1)
);
